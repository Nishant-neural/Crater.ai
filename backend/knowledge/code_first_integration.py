"""Code-first canonical machine model builder.

This is the redesign for global integration, agreed with Nishant on
31 Oct 2026: the canonical model is built in code from rows already
persisted in the database, not regenerated by an LLM.

Why this shape, in one paragraph: extraction already produced
structured rows (components, entities, facts, failure modes,
procedures, schematic nodes). Re-emitting all of them through an LLM
is the cost that made integration take 10 minutes on the 48-page
OMNIPRO manual and left it stuck at 93% with no snapshot. Code
grouping is O(rows), deterministic, auditable, and reversible:
source rows are never deleted, so a bad merge is undone by
tightening a rule and re-running integration, with no re-extraction.

Merge safety (the hard rule, not a similarity score):
- A name alone is never identity. Code merges only on exact
  normalised name + same entity type + no conflicting property.
- Different non-empty values for part_number, location, function,
  voltage or any other compared property veto a merge.
- Two rows from the same parts list with different item numbers
  are distinct instances and are never merged, even by adjudication.
- A row that matches more than one existing subgroup (for example
  a prose "Fan" with no item number, when Fan 44 and Fan 53 both
  exist) is kept as its own subgroup, not merged into the first
  match. That ambiguity becomes a cluster for adjudication.
- The LLM, when used at all, returns decisions only
  (merge / keep_separate / link) for ambiguous clusters, with a
  small token cap. Code vetoes any decision that would merge
  conflicting or same-list rows, and an uncertain or unparseable
  adjudication is dropped: the code model stands, with the link
  left open in the unresolved ledger.

This module deliberately does NOT build a deterministic entity
register: there is no pre-defined list of entities. New names
observed in source rows automatically become new canonical
entities. Grouping is derived from observed rows only.
"""
from __future__ import annotations

import hashlib
import json
import logging
import re
from typing import Any

logger = logging.getLogger(__name__)

_GENERIC_WORDS = {
    "mechanism", "assembly", "unit", "system", "device", "component",
    "part", "relay", "motor", "sensor", "switch", "module", "equipment",
}

_STOP_TOKENS = {"the", "a", "an", "and", "or", "of", "for", "to", "with"}


def norm_name(value: object) -> str:
    return re.sub(r"[^a-z0-9]+", " ", str(value or "").lower()).strip()


def norm_text(value: object) -> str:
    return norm_name(value)


def _slug(value: object) -> str:
    text = norm_name(value)
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-") or "unnamed"


def _tokens(value: object) -> set[str]:
    return {t for t in norm_name(value).split() if t not in _STOP_TOKENS}


def _chunk_ids_of(entity: dict[str, Any]) -> set[str]:
    """Chunk ids a canonical entity's source rows came from.

    Used only for same-chunk relation disambiguation: a canonical
    entity may have sources from several chunks, in which case its
    chunk set has several entries and it cannot be picked by chunk
    alone.
    """
    return {str(s.get("source_chunk_id")) for s in entity.get("sources") or []
            if isinstance(s, dict) and s.get("source_chunk_id")}


def _is_empty(value: Any) -> bool:
    return value is None or value == "" or value == {} or value == []


def _props_conflict(a: dict, b: dict) -> bool:
    if not isinstance(a, dict) or not isinstance(b, dict):
        return False
    for key, value in a.items():
        if key in b and not _is_empty(b[key]) and not _is_empty(value) and b[key] != value:
            return True
    return False


def _conflicting_keys(a: dict, b: dict) -> list[str]:
    keys: list[str] = []
    if not isinstance(a, dict) or not isinstance(b, dict):
        return keys
    for key, value in a.items():
        if key in b and not _is_empty(b[key]) and not _is_empty(value) and b[key] != value:
            keys.append(key)
    return keys


def source_fingerprint(context: dict[str, Any]) -> str:
    """Stable hash of the source rows, for the pre-LLM idempotency check."""
    parts: list[str] = []
    for category in sorted(context):
        rows = context[category]
        if not isinstance(rows, list):
            continue
        for row in sorted(rows, key=lambda r: str(r.get("source_id") if isinstance(r, dict) else r)):
            parts.append(category + ":" + json.dumps(row, sort_keys=True, default=str, ensure_ascii=False))
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()


def _evidence_for_row(row: dict[str, Any]) -> list[dict[str, Any]]:
    evidence = row.get("evidence")
    if isinstance(evidence, list) and evidence:
        out: list[dict[str, Any]] = []
        for item in evidence:
            if isinstance(item, dict) and item.get("fact"):
                out.append(item)
            elif isinstance(item, dict) and item.get("source_id"):
                out.append({"fact": f"Evidence reference to source record {item['source_id']}",
                            "claim_status": item.get("claim_status", "observed"),
                            "metadata": {"source_id": str(item["source_id"])}})
        if out:
            return out
    source_id = row.get("source_id") or ""
    name = row.get("name") or row.get("label") or "source record"
    return [{"fact": f"Source record {source_id}: {name}",
             "source_type": "text", "claim_status": "observed",
             "extraction_method": "code_first_integration",
             "metadata": {"source_id": str(source_id)} if source_id else {}}]


def _clean_properties(props: Any) -> dict[str, Any]:
    if not isinstance(props, dict):
        return {}
    return {str(k): v for k, v in props.items() if not _is_empty(v) or k == "part_number"}


def _entity_sources(context: dict[str, Any]) -> list[dict[str, Any]]:
    sources: list[dict[str, Any]] = []
    for row in context.get("universal_entities", []) or []:
        if not isinstance(row, dict) or not row.get("name"):
            continue
        sources.append({
            "source_id": str(row.get("source_id", "")),
            "name": str(row["name"]),
            "entity_type": str(row.get("entity_type") or "component"),
            "properties": _clean_properties(row.get("properties") or {}),
            "evidence": _evidence_for_row(row),
            "origin": "universal_entity",
            "source_chunk_id": row.get("source_chunk_id"),
        })
    for row in context.get("legacy_components", []) or []:
        if not isinstance(row, dict) or not row.get("name"):
            continue
        props: dict[str, Any] = {}
        if row.get("function"):
            props["function"] = row["function"]
        if row.get("location_description"):
            props["location_description"] = row["location_description"]
        if row.get("part_number"):
            props["part_number"] = row["part_number"]
        sources.append({
            "source_id": str(row.get("source_id", "")),
            "name": str(row["name"]),
            "entity_type": "component",
            "properties": props,
            "evidence": _evidence_for_row(row),
            "origin": "legacy_component",
            "source_chunk_id": row.get("source_chunk_id"),
        })
    for row in context.get("schematic_nodes", []) or []:
        if not isinstance(row, dict) or not row.get("label"):
            continue
        props: dict[str, Any] = {}
        if row.get("description"):
            props["description"] = row["description"]
        if row.get("bbox") is not None:
            props["bbox"] = row["bbox"]
        props["link_label"] = row["label"]
        props["link_normalized_label"] = norm_name(row["label"])
        sources.append({
            "source_id": str(row.get("source_id", "")),
            "name": str(row["label"]),
            "entity_type": str(row.get("symbol_type") or "other"),
            "properties": props,
            "evidence": _evidence_for_row(row),
            "origin": "schematic_node",
            "source_chunk_id": row.get("chunk_id"),
        })
    return sources


def _part_compatible(subgroup: dict[str, Any], row: dict[str, Any]) -> bool:
    """Part-number compatibility for a merge candidate.

    Both specific and equal: compatible. Both empty: compatible.
    One empty, one specific: compatible ONLY when they share a known
    source chunk -- i.e. the same extraction record recorded twice
    (universal + legacy tables for one chunk). A prose mention with
    no item number must never merge into a specific parts-list item
    from another chunk: that is how Fan (prose) would silently become
    Fan 44. When the chunk is unknown on either side, stay separate:
    the safe failure mode.
    """
    subgroup_parts = {str(s["properties"].get("part_number")) for s in subgroup["sources"] if s["properties"].get("part_number")}
    row_part = str(row["properties"].get("part_number") or "")
    if not subgroup_parts and not row_part:
        return True
    if row_part and subgroup_parts == {row_part}:
        return True
    if not row_part or not subgroup_parts:
        row_chunk = str(row.get("source_chunk_id") or "")
        return bool(row_chunk) and any(str(s.get("source_chunk_id") or "") == row_chunk for s in subgroup["sources"])
    return False


def _same_list_distinct(source_a: dict[str, Any], source_b: dict[str, Any]) -> bool:
    """True when both rows are items of the same source list with different item numbers.

    The parts-list signal available in context is part_number: in the
    OMNIPRO manual it carries item indices (page 43: 1-61) or quantities
    (page 46: mostly 1), never a manufacturer part number, so a
    different non-empty part_number in the same source chunk is treated
    as a distinct item, not as a conflict to be adjudicated away.
    """
    if source_a.get("source_chunk_id") and source_a.get("source_chunk_id") == source_b.get("source_chunk_id"):
        pa = source_a["properties"].get("part_number")
        pb = source_b["properties"].get("part_number")
        if pa and pb and str(pa) != str(pb):
            return True
    return False


def _group_entities(sources: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Group entity sources into canonical subgroups.

    Returns (canonical_entities, conflicts). A canonical entity is a
    subgroup of sources that could be merged safely. A source that
    matches more than one subgroup is kept as its own subgroup:
    that is ambiguity, not a reason to pick the first match.
    """
    groups: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for source in sources:
        key = (norm_name(source["name"]), norm_name(source["entity_type"]))
        groups.setdefault(key, []).append(source)

    canonical: list[dict[str, Any]] = []
    conflicts: list[dict[str, Any]] = []
    for (name_norm, type_norm), rows in groups.items():
        subgroups: list[dict[str, Any]] = []
        for row in rows:
            candidates: list[dict[str, Any]] = []
            for subgroup in subgroups:
                if _props_conflict(subgroup["properties"], row["properties"]):
                    continue
                if not _part_compatible(subgroup, row):
                    continue
                if any(_same_list_distinct(existing, row) for existing in subgroup["sources"]):
                    continue
                candidates.append(subgroup)
            if len(candidates) == 1:
                target = candidates[0]
                target["sources"].append(row)
                target["source_ids"].append(row["source_id"])
                for key, value in row["properties"].items():
                    target["properties"].setdefault(key, value)
                target["evidence"].extend(item for item in row["evidence"] if item not in target["evidence"])
            else:
                subgroups.append({
                    "name": row["name"],
                    "entity_type": row["entity_type"],
                    "properties": dict(row["properties"]),
                    "sources": [row],
                    "source_ids": [row["source_id"]],
                    "evidence": list(row["evidence"]),
                })
        # Assign stable canonical ids, with a distinguishing suffix
        # when one name+type splits into several subgroups.
        for index, subgroup in enumerate(subgroups):
            base = _slug(subgroup["name"])
            if len(subgroups) == 1:
                canonical_id = f"entity:{base}"
            else:
                distinguishing = ""
                part_numbers = {str(s["properties"].get("part_number")) for s in subgroup["sources"] if s["properties"].get("part_number")}
                if len(part_numbers) == 1:
                    distinguishing = _slug(next(iter(part_numbers)))
                else:
                    locations = {str(s["properties"].get("location_description")) for s in subgroup["sources"] if s["properties"].get("location_description")}
                    if len(locations) == 1:
                        distinguishing = _slug(next(iter(locations)))
                canonical_id = f"entity:{base}-{distinguishing}" if distinguishing else f"entity:{base}-{index + 1}"
            subgroup["id"] = canonical_id
            canonical.append(subgroup)
        if len(subgroups) > 1:
            # Record the conflict explicitly instead of hiding it:
            # every pair of subgroups disagrees on at least one property
            # (or on item number), otherwise they would have merged.
            seen_keys: dict[str, list[Any]] = {}
            for subgroup in subgroups:
                for key, value in subgroup["properties"].items():
                    seen_keys.setdefault(key, [])
                    if value not in seen_keys[key]:
                        seen_keys[key].append(value)
            for key, values in seen_keys.items():
                if len(values) > 1:
                    conflicts.append({
                        "id": f"conflict:{_slug(rows[0]['name'])}-{_slug(key)}",
                        "subject": rows[0]["name"],
                        "property": key,
                        "values": values,
                        "resolution": None,
                        "status": "unresolved",
                        "source_ids": sorted({sid for s in subgroups for sid in s["source_ids"]}),
                        "evidence": [],
                    })
    return canonical, conflicts


def _failure_mode_name(row: dict[str, Any]) -> str:
    # Legacy rows store "Name: symptom text" in one column; universal
    # rows store a clean name. The part before the first ": " is the name.
    raw = str(row.get("name") or row.get("symptom") or "")
    name = raw.split(": ", 1)[0].strip() if ": " in raw else raw.strip()
    return name or raw


def _failure_mode_sources(context: dict[str, Any]) -> list[dict[str, Any]]:
    sources: list[dict[str, Any]] = []
    for row in context.get("failure_modes", []) or []:
        if not isinstance(row, dict):
            continue
        sources.append({
            "source_id": str(row.get("source_id", "")),
            "name": _failure_mode_name(row),
            "symptoms": [str(row.get("symptom", ""))] if row.get("symptom") else [],
            "possible_causes": list(row.get("possible_causes") or []),
            "diagnostic_test": row.get("diagnostic_test") or "",
            "expected_observation": row.get("expected_observation") or "",
            "evidence": _evidence_for_row(row),
        })
    for row in context.get("universal_facts", []) or []:
        if not isinstance(row, dict) or row.get("fact_type") != "failure_mode":
            continue
        payload = row.get("payload") or {}
        if not isinstance(payload, dict):
            continue
        sources.append({
            "source_id": str(row.get("source_id", "")),
            "name": _failure_mode_name(payload),
            "symptoms": list(payload.get("symptoms") or []),
            "possible_causes": list(payload.get("possible_causes") or []),
            "diagnostic_test": payload.get("diagnostic_test") or "",
            "expected_observation": payload.get("expected_observation") or "",
            "evidence": _evidence_for_row(payload),
        })
    return sources


def build_code_first_payload(context: dict[str, Any]) -> dict[str, Any]:
    """Build the canonical payload in code. No LLM call happens here."""
    output_keys = ("entities", "relations", "ports", "quantities", "states", "events",
                   "behaviors", "constraints", "procedures", "failure_modes",
                   "simulation_rules", "conflicts", "unresolved_facts")
    payload: dict[str, Any] = {k: [] for k in output_keys}
    unresolved: list[dict[str, Any]] = []

    def add_unresolved(source_id: str, fact_type: str, original: Any, reason: str) -> None:
        unresolved.append({"source_id": str(source_id), "fact_type": fact_type,
                           "payload": original if isinstance(original, dict) else {"value": original},
                           "reason": reason})

    # --- Entities (universal + legacy + schematic, grouped together) ---
    sources = _entity_sources(context)
    canonical, conflicts = _group_entities(sources)
    payload["conflicts"] = conflicts

    canonical_by_id: dict[str, dict[str, Any]] = {}
    canonical_by_name: dict[str, list[dict[str, Any]]] = {}
    source_id_to_canonical: dict[str, str] = {}
    for entity in canonical:
        payload["entities"].append({
            "id": entity["id"], "name": entity["name"], "entity_type": entity["entity_type"],
            "properties": entity["properties"], "source_ids": sorted(set(entity["source_ids"])),
            "evidence": entity["evidence"],
            "merged_from": sorted(set(entity["source_ids"])),
        })
        canonical_by_id[entity["id"]] = entity
        canonical_by_name.setdefault(norm_name(entity["name"]), []).append(entity)
        for sid in entity["source_ids"]:
            source_id_to_canonical[sid] = entity["id"]

    # Map legacy component row ids and schematic node ids to names, for relations.
    component_name_by_id: dict[str, str] = {}
    for row in context.get("legacy_components", []) or []:
        if isinstance(row, dict) and row.get("source_id"):
            component_name_by_id[str(row["source_id"])] = str(row.get("name", ""))
    node_label_by_id: dict[str, str] = {}
    for row in context.get("schematic_nodes", []) or []:
        if isinstance(row, dict) and row.get("source_id"):
            node_label_by_id[str(row["source_id"])] = str(row.get("label", ""))

    def resolve_name_to_canonical(name: str, preferred_chunk_id: str = "") -> tuple[str | None, list[dict[str, Any]]]:
        candidates = canonical_by_name.get(norm_name(name), [])
        if len(candidates) == 1:
            return candidates[0]["id"], candidates
        if preferred_chunk_id:
            # Same-chunk disambiguation: the relation and its endpoints
            # were extracted from one chunk, in one extraction output,
            # so the names in that output co-refer to the entities in
            # that same output. Keep only the candidates whose source
            # rows came from the relation's own chunk. Exactly one
            # remaining means the chunk itself disambiguates; zero or
            # two-plus means it does not, and the link stays open.
            in_chunk = [c for c in candidates if preferred_chunk_id in _chunk_ids_of(c)]
            if len(in_chunk) == 1:
                return in_chunk[0]["id"], candidates
        return None, candidates

    def resolve_entity_id(entity_id: str, fallback_name: str = "", preferred_chunk_id: str = "") -> tuple[str | None, list[dict[str, Any]]]:
        if entity_id in canonical_by_id:
            return entity_id, [canonical_by_id[entity_id]]
        # Extraction entity ids are usually entity:<slug-of-name>.
        slug = str(entity_id or "").removeprefix("entity:").replace("-", " ")
        if slug:
            return resolve_name_to_canonical(slug, preferred_chunk_id)
        if fallback_name:
            return resolve_name_to_canonical(fallback_name, preferred_chunk_id)
        return None, []

    # --- Relations (universal + legacy + schematic edges) ---
    relation_rows: list[tuple[str, str, str, str, str, dict[str, Any]]] = []
    for row in context.get("universal_relations", []) or []:
        if isinstance(row, dict):
            relation_rows.append((str(row.get("source_id", "")), str(row.get("subject_name", "")),
                                  str(row.get("subject_id", "")), str(row.get("object_name", "")),
                                  str(row.get("object_id", "")), row))
    # Legacy and schematic relations are added below with name resolution;
    # they are handled separately because their endpoints are row ids.
    # Build relations from universal rows first.
    clusters: list[dict[str, Any]] = []
    for source_id, subject_name, subject_id, object_name, object_id, row in relation_rows:
        relation_type = str(row.get("relation_type") or "unspecified")
        preferred_chunk = str(row.get("source_chunk_id") or "")
        subject_canonical, subject_candidates = resolve_entity_id(subject_id, subject_name, preferred_chunk)
        object_canonical, object_candidates = resolve_entity_id(object_id, object_name, preferred_chunk)
        if subject_canonical and object_canonical:
            payload["relations"].append({
                "subject_id": subject_canonical, "subject_name": subject_name,
                "relation_type": relation_type, "object_id": object_canonical,
                "object_name": object_name, "description": row.get("description"),
                "source_ids": [source_id], "evidence": _evidence_for_row(row),
            })
        else:
            add_unresolved(source_id, "relation", row, "relation_endpoint_not_uniquely_resolvable")
            if len(subject_candidates) > 1 or len(object_candidates) > 1:
                clusters.append({"cluster_id": f"relation:{source_id}", "kind": "relation_endpoint",
                                 "subject_name": subject_name, "object_name": object_name,
                                 "relation_type": relation_type,
                                 "subject_candidates": [{"id": c["id"], "name": c["name"], "entity_type": c["entity_type"], "properties": c["properties"]} for c in subject_candidates],
                                 "object_candidates": [{"id": c["id"], "name": c["name"], "entity_type": c["entity_type"], "properties": c["properties"]} for c in object_candidates],
                                 "source_id": source_id})

    for row in context.get("legacy_relationships", []) or []:
        if not isinstance(row, dict):
            continue
        source_id = str(row.get("source_id", ""))
        from_name = component_name_by_id.get(str(row.get("from_component_id", "")), "")
        to_name = component_name_by_id.get(str(row.get("to_component_id", "")), "")
        relation_type = str(row.get("relation_type") or "unspecified")
        preferred_chunk = str(row.get("source_chunk_id") or "")
        subject_canonical, subject_candidates = resolve_name_to_canonical(from_name, preferred_chunk)
        object_canonical, object_candidates = resolve_name_to_canonical(to_name, preferred_chunk)
        if subject_canonical and object_canonical:
            payload["relations"].append({
                "subject_id": subject_canonical, "subject_name": from_name,
                "relation_type": relation_type, "object_id": object_canonical,
                "object_name": to_name, "description": row.get("description"),
                "source_ids": [source_id], "evidence": _evidence_for_row(row),
            })
        else:
            add_unresolved(source_id, "relation", row, "relation_endpoint_not_uniquely_resolvable")
            if len(subject_candidates) > 1 or len(object_candidates) > 1:
                clusters.append({"cluster_id": f"relation:{source_id}", "kind": "relation_endpoint",
                                 "subject_name": from_name, "object_name": to_name,
                                 "relation_type": relation_type,
                                 "subject_candidates": [{"id": c["id"], "name": c["name"], "entity_type": c["entity_type"], "properties": c["properties"]} for c in subject_candidates],
                                 "object_candidates": [{"id": c["id"], "name": c["name"], "entity_type": c["entity_type"], "properties": c["properties"]} for c in object_candidates],
                                 "source_id": source_id})

    for row in context.get("schematic_edges", []) or []:
        if not isinstance(row, dict):
            continue
        source_id = str(row.get("source_id", ""))
        from_label = node_label_by_id.get(str(row.get("from_node_id", "")), "")
        to_label = node_label_by_id.get(str(row.get("to_node_id", "")), "")
        wire_type = str(row.get("wire_type") or "unknown")
        subject_canonical, subject_candidates = resolve_name_to_canonical(from_label)
        object_canonical, object_candidates = resolve_name_to_canonical(to_label)
        if subject_canonical and object_canonical:
            payload["relations"].append({
                "subject_id": subject_canonical, "subject_name": from_label,
                "relation_type": wire_type, "object_id": object_canonical,
                "object_name": to_label, "description": row.get("label"),
                "source_ids": [source_id], "evidence": _evidence_for_row(row),
            })
        else:
            add_unresolved(source_id, "schematic_edge", row, "schematic_edge_endpoint_not_uniquely_resolvable")

    # --- Dedupe relations: a universal row and its legacy copy are the
    # same logical relation (same endpoints, same type); keep one and
    # union the source ids and evidence, as failure modes and
    # procedures already do. Without this, resolving both copies
    # would put the same relation in the snapshot twice.
    _seen_relations: dict[tuple[str, str, str], dict[str, Any]] = {}
    _deduped_relations: list[dict[str, Any]] = []
    for _rel in payload["relations"]:
        _key = (str(_rel.get("subject_id", "")), str(_rel.get("relation_type", "")),
                str(_rel.get("object_id", "")))
        _existing = _seen_relations.get(_key)
        if _existing is None:
            _seen_relations[_key] = _rel
            _deduped_relations.append(_rel)
        else:
            _existing["source_ids"] = sorted(set(_existing.get("source_ids", [])) | set(_rel.get("source_ids", [])))
            _existing["evidence"] = list(_existing.get("evidence", [])) + [
                item for item in _rel.get("evidence", []) if item not in _existing.get("evidence", [])]
            if not _existing.get("description") and _rel.get("description"):
                _existing["description"] = _rel["description"]
    payload["relations"] = _deduped_relations

    # --- Ports / quantities / states / events / constraints from universal facts ---
    for row in context.get("universal_facts", []) or []:
        if not isinstance(row, dict):
            continue
        fact_type = str(row.get("fact_type", ""))
        payload_dict = row.get("payload") or {}
        if not isinstance(payload_dict, dict):
            continue
        if fact_type == "failure_mode":
            continue  # handled with legacy failure modes below
        if fact_type in ("port", "quantity", "state", "event", "constraint"):
            entity_id = str(payload_dict.get("entity_id") or "")
            entity_name = str(payload_dict.get("entity_name") or payload_dict.get("subject_name") or "")
            canonical_id, _ = resolve_entity_id(entity_id, entity_name)
            if not canonical_id:
                # Quantities are the exception, mirroring validation.py:
                # a specification quantity with a real name and a non-empty
                # value is a fact about a mode / the whole machine even
                # when no canonical entity resolves ("Mig Power Input",
                # 120 VAC, entity_id "unresolved:entity"). Keep it with
                # that placeholder untouched and its subject_name
                # preserved, so it reaches the snapshot instead of being
                # dropped twice (once by quarantine, once here). A
                # quantity with an empty value or a placeholder name is
                # not a measurement (a unit glossary) and stays
                # unresolved, as before. Ports/states/events/constraints
                # keep the old behaviour: unresolvable means unresolved.
                if fact_type == "quantity":
                    q_name = str(payload_dict.get("name") or entity_name or "").strip()
                    q_value = payload_dict.get("value")
                    q_value_text = "" if q_value is None else str(q_value).strip()
                    if q_name and q_name != "Unresolved item" and q_value_text:
                        item = dict(payload_dict)
                        item["entity_id"] = entity_id or "unresolved:entity"
                        item["subject_name"] = entity_name or q_name
                        item["source_ids"] = [str(row.get("source_id", ""))]
                        item.setdefault("evidence", _evidence_for_row(payload_dict))
                        if not item.get("id"):
                            item["id"] = f"quantity:{row.get('fact_key') or row.get('source_id')}"
                        if not item.get("name"):
                            item["name"] = q_name
                        payload["quantities"].append(item)
                        continue
                add_unresolved(str(row.get("source_id", "")), fact_type, row, "fact_entity_not_uniquely_resolvable")
                continue
            item = dict(payload_dict)
            item["entity_id"] = canonical_id
            item["source_ids"] = [str(row.get("source_id", ""))]
            item.setdefault("evidence", _evidence_for_row(payload_dict))
            target_key = {"port": "ports", "quantity": "quantities", "state": "states",
                          "event": "events", "constraint": "constraints"}[fact_type]
            if fact_type == "quantity":
                item.setdefault("id", item.get("id") or f"quantity:{row.get('fact_key') or row.get('source_id')}")
                item.setdefault("name", item.get("name") or str(row.get("fact_key") or ""))
            payload[target_key].append(item)
        elif fact_type == "procedure":
            # Procedures from universal facts are handled with legacy procedures below.
            continue
        elif fact_type == "behavior":
            continue  # behaviors come from the behaviors category below
        else:
            # Unknown fact types are not dropped silently.
            add_unresolved(str(row.get("source_id", "")), fact_type, row, "fact_type_not_canonicalized_by_code_first")

    # Ports / states embedded in universal entities.
    for row in context.get("universal_entities", []) or []:
        if not isinstance(row, dict):
            continue
        canonical_id, _ = resolve_name_to_canonical(str(row.get("name", "")))
        if not canonical_id:
            continue
        for port in row.get("ports") or []:
            if isinstance(port, dict):
                item = dict(port)
                item["entity_id"] = canonical_id
                item["source_ids"] = [str(row.get("source_id", ""))]
                payload["ports"].append(item)
        for state in row.get("states") or []:
            if isinstance(state, dict):
                item = dict(state)
                item["entity_id"] = canonical_id
                item["source_ids"] = [str(row.get("source_id", ""))]
                payload["states"].append(item)

    # --- Behaviors ---
    for row in context.get("behaviors", []) or []:
        if not isinstance(row, dict):
            continue
        subject_name = str(row.get("subject_name", ""))
        subject_canonical, _ = resolve_name_to_canonical(subject_name)
        payload["behaviors"].append({
            "id": f"behavior:{row.get('source_id')}",
            "subject_id": subject_canonical or str(row.get("subject_id") or f"unresolved:behavior-subject:{_slug(subject_name)}"),
            "subject_name": subject_name,
            "description": str(row.get("description", "")),
            "source_ids": [str(row.get("source_id", ""))],
            "evidence": _evidence_for_row(row),
        })

    # --- Procedures (legacy + universal procedure facts, deduped) ---
    procedure_sources: list[dict[str, Any]] = []
    for row in context.get("procedures", []) or []:
        if isinstance(row, dict) and row.get("name"):
            procedure_sources.append({"source_id": str(row.get("source_id", "")), "name": str(row["name"]),
                                      "procedure_type": str(row.get("procedure_type") or "maintenance"),
                                      "steps": list(row.get("steps") or []), "evidence": _evidence_for_row(row)})
    for row in context.get("universal_facts", []) or []:
        if isinstance(row, dict) and row.get("fact_type") == "procedure":
            payload_dict = row.get("payload") or {}
            if isinstance(payload_dict, dict) and payload_dict.get("name"):
                procedure_sources.append({"source_id": str(row.get("source_id", "")), "name": str(payload_dict["name"]),
                                          "procedure_type": str(payload_dict.get("procedure_type") or "maintenance"),
                                          "steps": list(payload_dict.get("steps") or []), "evidence": _evidence_for_row(payload_dict)})
    procedure_groups: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for proc in procedure_sources:
        procedure_groups.setdefault((norm_name(proc["name"]), norm_name(proc["procedure_type"])), []).append(proc)
    for (name_norm, _type_norm), rows in procedure_groups.items():
        subgroups: list[dict[str, Any]] = []
        for proc in rows:
            merged = False
            for subgroup in subgroups:
                steps_a, steps_b = set(subgroup["steps"]), set(proc["steps"])
                if not steps_a or not steps_b or steps_a <= steps_b or steps_b <= steps_a:
                    subgroup["source_ids"].append(proc["source_id"])
                    subgroup["steps"] = list(dict.fromkeys(subgroup["steps"] + proc["steps"]))
                    subgroup["evidence"].extend(item for item in proc["evidence"] if item not in subgroup["evidence"])
                    merged = True
                    break
            if not merged:
                subgroups.append({"name": proc["name"], "procedure_type": proc["procedure_type"],
                                  "steps": list(proc["steps"]), "source_ids": [proc["source_id"]],
                                  "evidence": list(proc["evidence"])})
        for index, subgroup in enumerate(subgroups):
            proc_id = f"procedure:{_slug(subgroup['name'])}" if len(subgroups) == 1 else f"procedure:{_slug(subgroup['name'])}-{index + 1}"
            payload["procedures"].append({"id": proc_id, "name": subgroup["name"],
                                          "procedure_type": subgroup["procedure_type"], "steps": subgroup["steps"],
                                          "entity_ids": [], "source_ids": sorted(set(subgroup["source_ids"])),
                                          "evidence": subgroup["evidence"]})

    # --- Failure modes (legacy + universal, deduped by name, causes unioned) ---
    failure_groups: dict[str, dict[str, Any]] = {}
    for fm in _failure_mode_sources(context):
        key = norm_name(fm["name"])
        if not key:
            continue
        existing = failure_groups.get(key)
        if existing is None:
            failure_groups[key] = {"name": fm["name"], "symptoms": list(fm["symptoms"]),
                                   "possible_causes": list(fm["possible_causes"]),
                                   "diagnostic_test": fm["diagnostic_test"],
                                   "expected_observation": fm["expected_observation"],
                                   "source_ids": [fm["source_id"]], "evidence": list(fm["evidence"])}
        else:
            existing["source_ids"].append(fm["source_id"])
            existing["symptoms"] = list(dict.fromkeys(existing["symptoms"] + fm["symptoms"]))
            existing["possible_causes"] = list(dict.fromkeys(existing["possible_causes"] + fm["possible_causes"]))
            if not existing["diagnostic_test"] and fm["diagnostic_test"]:
                existing["diagnostic_test"] = fm["diagnostic_test"]
            if not existing["expected_observation"] and fm["expected_observation"]:
                existing["expected_observation"] = fm["expected_observation"]
            existing["evidence"].extend(item for item in fm["evidence"] if item not in existing["evidence"])
    for key, fm in failure_groups.items():
        payload["failure_modes"].append({
            "id": f"failure:{_slug(fm['name'])}", "name": fm["name"],
            "symptoms": fm["symptoms"], "possible_causes": fm["possible_causes"],
            "diagnostic_test": fm["diagnostic_test"], "expected_observation": fm["expected_observation"],
            "repair_procedure_id": None, "entity_ids": [],
            "source_ids": sorted(set(fm["source_ids"])), "evidence": fm["evidence"],
        })

    # --- Conflicting same-name groups become adjudication clusters ---
    # Recompute groups by name+type to find split subgroups.
    name_type_to_subgroups: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for entity in canonical:
        name_type_to_subgroups.setdefault((norm_name(entity["name"]), norm_name(entity["entity_type"])), []).append(entity)
    for (name_norm, _type_norm), subgroups in name_type_to_subgroups.items():
        if len(subgroups) > 1:
            clusters.append({"cluster_id": f"conflict:{_slug(subgroups[0]['name'])}", "kind": "conflicting_same_name",
                             "name": subgroups[0]["name"],
                             "candidates": [{"id": s["id"], "name": s["name"], "entity_type": s["entity_type"],
                                             "properties": s["properties"], "source_ids": s["source_ids"]} for s in subgroups]})

    # --- Synonym candidates: prose reference vs a specific parts item ---
    # Only when: same entity type, shared first token, one side has no
    # item number (prose) and the other has one (parts item), and no
    # conflicting property. Both sides being parts items with different
    # item numbers is never a candidate: those are distinct instances.
    canonical_list = list(canonical)
    seen_pairs: set[tuple[str, str]] = set()
    for i, first in enumerate(canonical_list):
        for second in canonical_list[i + 1:]:
            if norm_name(first["entity_type"]) != norm_name(second["entity_type"]):
                continue
            first_tokens, second_tokens = _tokens(first["name"]), _tokens(second["name"])
            if not first_tokens or not second_tokens:
                continue
            if norm_name(first["name"]) == norm_name(second["name"]):
                continue
            # Synonym evidence, in decreasing strength: one name's tokens
            # are a subset of the other's (Pump P1 / Hydraulic Pump P1),
            # the names share a distinctive first token (MIG Gun /
            # MIG Welding Torch), or their functions share words.
            first_tokens_set, second_tokens_set = _tokens(first["name"]), _tokens(second["name"])
            shared_first = (norm_name(first["name"]).split() or [""])[0] == (norm_name(second["name"]).split() or [""])[0]
            function_overlap = len(_tokens(first["properties"].get("function", "")) & _tokens(second["properties"].get("function", ""))) >= 2
            if not (first_tokens_set <= second_tokens_set or second_tokens_set <= first_tokens_set or shared_first or function_overlap):
                continue
            if _props_conflict(first["properties"], second["properties"]):
                continue
            part_first = first["properties"].get("part_number")
            part_second = second["properties"].get("part_number")
            if part_first and part_second:
                continue  # both specific items: distinct unless exact name
            pair = tuple(sorted([first["id"], second["id"]]))
            if pair in seen_pairs:
                continue
            seen_pairs.add(pair)
            clusters.append({"cluster_id": f"synonym:{first['id']}--{second['id']}", "kind": "synonym_candidate",
                             "candidates": [{"id": first["id"], "name": first["name"], "entity_type": first["entity_type"], "properties": first["properties"], "source_ids": first["source_ids"]},
                                            {"id": second["id"], "name": second["name"], "entity_type": second["entity_type"], "properties": second["properties"], "source_ids": second["source_ids"]}]})

    # Cap adjudication clusters so one manual cannot turn into many calls:
    # the prompt is one call regardless, but a huge cluster list would
    # itself become a re-emission problem. 50 is far above OMNIPRO's count.
    clusters = clusters[:50]

    # --- Expert knowledge: tracked, not silently dropped ---
    for row in context.get("expert_knowledge", []) or []:
        if isinstance(row, dict):
            add_unresolved(str(row.get("source_id", "")), "expert_knowledge", row,
                           "expert_knowledge_not_canonicalized_by_code_first")

    payload["unresolved_facts"] = unresolved
    return {"payload": payload, "clusters": clusters,
            "canonical_by_id": canonical_by_id, "canonical_by_name": canonical_by_name}


def code_first_completeness(context: dict[str, Any], payload: dict[str, Any]) -> dict[str, Any]:
    """Honest audit: canonicalized rows only count as accounted.

    Unlike the old check, an unresolved row does NOT count as
    accounted. It is tracked, not lost, but the model is not claimed
    complete while it exists. That is the fix for the old OMNIPRO
    snapshot claiming 76/76 complete with open unresolved rows.
    """
    ledger: dict[str, tuple[str, dict[str, Any]]] = {}
    for kind, rows in context.items():
        if not isinstance(rows, list):
            continue
        for row in rows:
            if isinstance(row, dict) and row.get("source_id"):
                ledger[str(row["source_id"])] = (kind, row)
    accounted: set[str] = set()
    for key, rows in payload.items():
        if key == "unresolved_facts" or not isinstance(rows, list):
            continue
        for row in rows:
            if isinstance(row, dict):
                accounted.update(str(x) for x in row.get("source_ids", []) if x)
    missing_ids = sorted(set(ledger) - accounted)
    return {"source_total": len(ledger), "accounted_total": len(accounted & set(ledger)),
            "missing_count": len(missing_ids), "missing_source_ids": missing_ids,
            "complete": not missing_ids, "unresolved_count": len(payload.get("unresolved_facts", []) or [])}


def adjudicate_clusters(clusters: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """One small LLM call, decisions only. Returns [] on any failure.

    A failure here never fails integration: the code model stands
    and ambiguous links stay open.
    """
    if not clusters:
        return []
    try:
        from backend.llm import gateway
        prompt = (
            "You are adjudicating ambiguous entity identity for an industrial "
            "machine knowledge model. For each cluster, decide ONLY from the "
            "evidence shown. Merge only if the candidates are provably the "
            "same physical component. Otherwise keep them separate, or, for a "
            "relation_endpoint cluster, link the relation to exactly one "
            "candidate. Never merge two candidates with different non-empty "
            "part numbers, locations, or voltages. Return ONLY JSON in this "
            "shape: {\"decisions\": [{\"cluster_id\": \"...\", \"action\": "
            "\"merge|keep_separate|link\", \"kept_id\": \"...\", "
            "\"linked_id\": \"...\"}]}. A merge decision must name a kept_id "
            "that is one of the candidates. A link decision must name a "
            "linked_id that is one of the candidates.\n\nCLUSTERS:\n"
            + json.dumps(clusters, ensure_ascii=False, separators=(",", ":"))[:60000]
        )
        raw = gateway.complete("integration", messages=[{"role": "user", "content": prompt}], max_tokens=2000)
    except Exception as exc:
        # Log, don't swallow silently: a failed adjudication call is
        # the difference between "the model declined to link" and
        # "the call never completed", and the snapshot alone cannot
        # tell them apart.
        logger.warning("Adjudication call failed for %d clusters: %s", len(clusters), exc)
        return []
    if not raw:
        logger.warning("Adjudication returned an empty response for %d clusters", len(clusters))
        return []
    try:
        parsed = json.loads(raw)
    except Exception:
        start, end = raw.find("{"), raw.rfind("}")
        if start < 0 or end <= start:
            logger.warning("Adjudication response was unparseable for %d clusters", len(clusters))
            return []
        try:
            parsed = json.loads(raw[start:end + 1])
        except Exception:
            logger.warning("Adjudication response was unparseable for %d clusters", len(clusters))
            return []
    decisions = parsed.get("decisions") if isinstance(parsed, dict) else None
    if not isinstance(decisions, list):
        logger.warning("Adjudication response had no decisions list for %d clusters", len(clusters))
        return []
    logger.info("Adjudication returned %d decisions for %d clusters", len(decisions), len(clusters))
    return decisions


def apply_adjudication(state: dict[str, Any], decisions: list[dict[str, Any]]) -> None:
    """Apply adjudication decisions to a code-first payload, with code vetoes."""
    payload = state["payload"]
    canonical_by_id = state["canonical_by_id"]
    for decision in decisions:
        if not isinstance(decision, dict):
            continue
        cluster_id = str(decision.get("cluster_id", ""))
        action = str(decision.get("action", ""))
        cluster = next((c for c in state["clusters"] if c["cluster_id"] == cluster_id), None)
        if cluster is None:
            continue
        candidates = cluster.get("candidates") or cluster.get("subject_candidates") or []
        # Relation clusters carry subject/object candidate lists separately.
        if action == "merge" and cluster.get("kind") in ("conflicting_same_name", "synonym_candidate"):
            kept_id = str(decision.get("kept_id", ""))
            candidate_ids = [str(c.get("id")) for c in cluster.get("candidates", []) if isinstance(c, dict)]
            if kept_id not in candidate_ids:
                continue
            kept = canonical_by_id.get(kept_id)
            others = [canonical_by_id[cid] for cid in candidate_ids if cid != kept_id and cid in canonical_by_id]
            # Veto: merging candidates with different non-empty part numbers,
            # locations or other distinguishing properties is never allowed,
            # even if the LLM proposes it.
            veto = False
            for other in others:
                if _props_conflict(kept["properties"], other["properties"]):
                    veto = True
                    break
                if any(_same_list_distinct(existing, other_row) for existing in kept["sources"] for other_row in other["sources"]):
                    veto = True
                    break
            if veto or not others:
                continue
            # Merge others into kept, in code.
            for other in others:
                kept["source_ids"] = sorted(set(kept["source_ids"]) | set(other["source_ids"]))
                for key, value in other["properties"].items():
                    kept["properties"].setdefault(key, value)
                kept["evidence"].extend(item for item in other["evidence"] if item not in kept["evidence"])
            # Rewrite payload entities and relations.
            payload["entities"] = [e for e in payload["entities"] if e["id"] not in [o["id"] for o in others]]
            for entity in payload["entities"]:
                if entity["id"] == kept_id:
                    entity["source_ids"] = kept["source_ids"]
                    entity["properties"] = kept["properties"]
                    entity["evidence"] = kept["evidence"]
            removed_ids = {o["id"] for o in others}
            for relation in payload["relations"]:
                if relation.get("subject_id") in removed_ids:
                    relation["subject_id"] = kept_id
                if relation.get("object_id") in removed_ids:
                    relation["object_id"] = kept_id
            for other in others:
                canonical_by_id.pop(other["id"], None)
        elif action == "link" and cluster.get("kind") == "relation_endpoint":
            linked_id = str(decision.get("linked_id", ""))
            source_id = str(cluster.get("source_id", ""))
            # Find the unresolved relation for this cluster and promote it.
            unresolved = payload.get("unresolved_facts", [])
            target = next((u for u in unresolved if str(u.get("source_id")) == source_id), None)
            if target is None:
                continue
            subject_candidates = [str(c.get("id")) for c in cluster.get("subject_candidates", []) if isinstance(c, dict)]
            object_candidates = [str(c.get("id")) for c in cluster.get("object_candidates", []) if isinstance(c, dict)]
            if linked_id not in subject_candidates + object_candidates:
                continue
            original = target.get("payload") or {}
            # Determine which endpoint was ambiguous by checking which side
            # already resolved uniquely in the original row is not possible
            # from the cluster alone, so link both sides only when the
            # linked id matches a candidate on exactly one side.
            # For safety, only promote when exactly one side is ambiguous:
            # the other side must already be a canonical id in the payload
            # relations, which code-first did not create, so this branch is
            # intentionally conservative: it requires the linked id to be
            # the sole candidate on one side and the other side to have a
            # single candidate as well in the cluster data.
            # In practice relation clusters in this build carry both sides;
            # if both sides have multiple candidates, keep it unresolved.
            if len(subject_candidates) == 1 and len(object_candidates) > 1 and linked_id in object_candidates:
                subject_id, object_id = subject_candidates[0], linked_id
            elif len(object_candidates) == 1 and len(subject_candidates) > 1 and linked_id in subject_candidates:
                subject_id, object_id = linked_id, object_candidates[0]
            else:
                continue
            relation_type = cluster.get("relation_type", "unspecified")
            # Do not create a second copy of a relation code already
            # resolved (e.g. by same-chunk disambiguation): fold this
            # source into the existing relation and drop the unresolved
            # record, so completeness stays honest.
            existing = next((r for r in payload["relations"]
                             if r.get("subject_id") == subject_id
                             and r.get("relation_type") == relation_type
                             and r.get("object_id") == object_id), None)
            if existing is not None:
                existing["source_ids"] = sorted(set(existing.get("source_ids", [])) | {source_id})
                payload["unresolved_facts"] = [u for u in unresolved if str(u.get("source_id")) != source_id]
                continue
            payload["relations"].append({
                "subject_id": subject_id, "subject_name": cluster.get("subject_name", ""),
                "relation_type": relation_type,
                "object_id": object_id, "object_name": cluster.get("object_name", ""),
                "description": original.get("description") if isinstance(original, dict) else None,
                "source_ids": [source_id], "evidence": [],
            })
            payload["unresolved_facts"] = [u for u in unresolved if str(u.get("source_id")) != source_id]
