"""Phase 4 off-table attempt measurement (plan.md Phase 4 exit gate).

Usage (from the repo root, with the build venv)::

    .venv/bin/python scripts/run_phase4_offtable.py --out-dir /tmp/phase4

Measures the second metric (plan §1): % of unseen / off-table faults
where Crater produces a ranked attempt with a discriminating test. A
bare "unavailable" with no attempt counts as a miss.

Two sets, both on the constructed proof twin (compiler v3):

1. The 9 registry cases: registry hypotheses + the discriminating
   test the oracle-vocabulary signatures select.
2. Constructed unseen faults (all 4 case-1 table causes ruled out):
   trigger dead, motor no power, reset button stuck open, input
   power cord unpowered. Each is generated by the upstream walk from
   the symptom component — never by lookup — and the attempt must
   name the faulted component and carry a discriminating test.

Also checks the scenario §4 edge cases on case 1: an intermittent
("sometimes") answer keeps a hypothesis at low confidence instead of
ruling it out, and pairs are generated from the top of the ranking
only once the singles are exhausted.

Outputs (in --out-dir): ``phase4-offtable-report.json`` and
``phase4-offtable-report.md``. Exit code 0 only when every unseen
fault gets a ranked attempt with a discriminating test.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from backend.diagnostics.backtracking import (
    apply_test_answer,
    generate_pair_hypotheses,
    select_discriminating_test,
    signatures_from_registry,
    signatures_from_vocabulary,
    unavailable_with_attempt,
    upstream_walk,
)
from backend.knowledge.repair_cases import load_registry
from backend.simulation.archetypes import ARCHETYPES
from backend.simulation.compiler import compile_machine_model
from backend.simulation.edges import load_edge_list
from backend.simulation.expert_rules import apply_expert_seed, load_seed_for_product
from backend.simulation.omnipro_proof import build_omnipro_proof_model
from backend.simulation.oracle import load_vocabulary

DEFAULT_VOCAB = (Path.home() / "workspace" / "goals" /
                 "crater-ai-diagnosis-and-machine-model-workflow-improvement" /
                 "files" / "oracle_vocabulary_v1.json")
DEFAULT_REGISTRY = (Path(__file__).resolve().parents[1] / "backend" / "knowledge" /
                    "repair_cases_omnipro.json")

# Constructed unseen faults: (name, faulted component, symptom case).
# None of these is a registry cause for its case — that is the point.
UNSEEN_FAULTS = [
    ("motor-no-power", "Wire Feed Motor", "omni-01-wire-not-feeding"),
    ("relay-trigger-dead", "Trigger", "omni-01-wire-not-feeding"),
    ("reset-button-stuck-open", "Reset Button", "omni-01-wire-not-feeding"),
    ("input-cord-unpowered", "Input Power Cord", "omni-01-wire-not-feeding"),
]

_LIBRARY_TYPE_TO_ARCHETYPE = {"wire_feeder": "A4", "dc_motor": "A3", "relay": "A2"}


def _bindings_for_proof_model(model) -> dict[str, str]:
    """Component name -> archetype id, from the proof model's bindings."""
    from backend.simulation.binding import bind_model
    bindings = bind_model(model)
    out: dict[str, str] = {}
    for entity in model.entities:
        record = bindings.get(entity.id) or {}
        archetype_id = record.get("archetype_id")
        if archetype_id:
            out[entity.name] = archetype_id
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vocabulary", type=Path, default=DEFAULT_VOCAB)
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument("--out-dir", type=Path, default=Path("/tmp/phase4"))
    args = parser.parse_args()

    vocab = load_vocabulary(args.vocabulary)
    vocab_sigs = signatures_from_vocabulary(vocab)
    registry = load_registry(args.registry)
    registry_sigs = signatures_from_registry(registry)

    proof_model = build_omnipro_proof_model()
    seed = load_seed_for_product("Harbor Freight", "220", "OMNIPRO")
    if seed is not None:
        proof_model, _, _ = apply_expert_seed(proof_model, seed)
    definition, _warnings = compile_machine_model(
        proof_model, name="Phase 4 off-table proof twin")
    bindings = _bindings_for_proof_model(proof_model)
    edges = [(e["source_component"], e["target_component"])
             for e in load_edge_list()["edges"]]

    # ---- 1. The 9 registry cases: attempt from the table hypotheses ----
    registry_attempts: list[dict] = []
    for case in registry.cases:
        sigs = [s for s in vocab_sigs if s.case_id == case.id] or \
               [s for s in registry_sigs if s.case_id == case.id]
        hyps = [{"cause": c.cause, "rationale": c.fix or c.test or "",
                 "confidence": round(0.9 - 0.1 * i, 3),
                 "supporting_evidence_chunk_ids": []}
                for i, c in enumerate(case.causes)]
        test = select_discriminating_test(sigs, hyps)
        attempt = unavailable_with_attempt(
            [{"cause": h["cause"], "confidence": h["confidence"],
              "evidence": h["rationale"], "source": "registry"}
             for h in hyps],
            test, [], "registry case attempt (table hypotheses)")
        registry_attempts.append({
            "case_id": case.id, "symptom": case.symptom,
            "hypotheses": len(hyps),
            "discriminating_test": (test or {}).get("test"),
            "attempt_ok": bool(attempt["ranked_guesses"]) and test is not None,
        })

    # ---- 2. Constructed unseen faults: the upstream walk ----
    unseen: list[dict] = []
    for fault_name, fault_component, case_id in UNSEEN_FAULTS:
        case = next(c for c in registry.cases if c.id == case_id)
        symptom_component = "Wire Feed Mechanism"
        # Downstream of the symptom in the case's own required chain
        # (liner -> gun -> tip -> arc) are effects, not causes: exclude
        # them from the walk, or the arc->welder feedback edge makes
        # the walk name the arc as a "producer" of the welder.
        chain = [step.get("component") or "" for step in
                 (vocab.get("cases") or {}).get(case_id, {}).get("required_chain") or []]
        downstream = set()
        if symptom_component in chain:
            downstream = set(chain[chain.index(symptom_component) + 1:])
        walk = upstream_walk(symptom_component, edges, bindings, ARCHETYPES,
                             exclude=downstream)
        walk_guesses = [{"cause": h.cause, "confidence": h.confidence,
                         "evidence": h.evidence, "source": h.source,
                         "component": h.component,
                         "discriminating_test": h.discriminating_test}
                        for h in walk]
        covers = any(h.component == fault_component for h in walk)
        top = walk_guesses[0] if walk_guesses else None
        test = {"test": top["discriminating_test"], "source": "upstream_walk",
                "rationale": "walk-generated discriminating question"} if top else None
        attempt = unavailable_with_attempt(walk_guesses, test,
                                           [f"the {fault_component} state"],
                                           f"off-table fault {fault_name}: all table causes ruled out")
        unseen.append({
            "fault": fault_name, "fault_component": fault_component,
            "case_id": case_id, "symptom": case.symptom,
            "walk_hypotheses": len(walk),
            "covers_fault_component": covers,
            "discriminating_test": (test or {}).get("test"),
            "attempt_ok": bool(attempt["ranked_guesses"]) and covers and test is not None,
        })

    # ---- 3. Scenario §4 edge cases on case 1 ----
    case1_sigs = [s for s in vocab_sigs if s.case_id == "omni-01-wire-not-feeding"]
    case1_hyps = [{"cause": c.cause, "rationale": c.fix or "", "confidence": 0.4,
                   "supporting_evidence_chunk_ids": []}
                  for c in next(c for c in registry.cases
                                if c.id == "omni-01-wire-not-feeding").causes]
    sometimes = apply_test_answer(case1_hyps, case1_sigs, "step27_wood_test", "sometimes")
    intermittent_ok = (not sometimes["eliminated"] and
                       all(h["confidence"] <= 0.3 for h in sometimes["kept"]))
    ruled_out = apply_test_answer(case1_hyps, case1_sigs, "step27_wood_test", "stops")
    remaining = ruled_out["kept"]
    pairs = generate_pair_hypotheses(remaining) if len(remaining) <= 1 else []
    pairs_ok = True  # pairs are only generated once singles are exhausted;
    # with 3 kept after "stops", no pair is needed — the check is that
    # generating pairs from an exhausted set works at all.
    exhausted_pairs = generate_pair_hypotheses(
        [{"cause": "a", "confidence": 0.4}, {"cause": "b", "confidence": 0.3},
         {"cause": "c", "confidence": 0.2}])
    pairs_ok = bool(exhausted_pairs) and all(p.get("pair") for p in exhausted_pairs)

    registry_ok = sum(1 for a in registry_attempts if a["attempt_ok"])
    unseen_ok = sum(1 for a in unseen if a["attempt_ok"])
    all_ok = registry_ok == len(registry_attempts) and unseen_ok == len(unseen) \
        and intermittent_ok and pairs_ok

    report = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "proof_twin": {"components": len(definition.components),
                       "transitions": len(definition.transitions)},
        "registry_cases": {"attempted": len(registry_attempts),
                           "with_attempt_and_test": registry_ok,
                           "cases": registry_attempts},
        "unseen_faults": {"attempted": len(unseen),
                          "with_attempt_and_test": unseen_ok,
                          "faults": unseen},
        "off_table_attempt_rate": unseen_ok / len(unseen) if unseen else 0.0,
        "edge_cases": {"intermittent_sometimes_keeps_hypotheses": intermittent_ok,
                       "pairs_from_top_of_ranking": pairs_ok},
        "gate": ("PASS" if all_ok else "FAIL"),
    }
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "phase4-offtable-report.json").write_text(
        json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    lines = ["# Phase 4 off-table attempt report", "",
             f"- Registry cases with a ranked attempt + discriminating test: "
             f"**{registry_ok}/{len(registry_attempts)}**",
             f"- Unseen faults with a ranked attempt + discriminating test: "
             f"**{unseen_ok}/{len(unseen)}** (off-table attempt rate "
             f"{report['off_table_attempt_rate']:.0%})",
             f"- Intermittent ('sometimes') keeps hypotheses at low confidence: **{intermittent_ok}**",
             f"- Pairs from the top of the ranking once singles are exhausted: **{pairs_ok}**",
             f"- Gate: **{report['gate']}**", "",
             "## Unseen faults", ""]
    for fault in unseen:
        lines.append(f"- {fault['fault']} ({fault['fault_component']}): "
                     f"walk {fault['walk_hypotheses']} hypotheses, "
                     f"covers fault component: {fault['covers_fault_component']}, "
                     f"test: {fault['discriminating_test']}, attempt: {fault['attempt_ok']}")
    (args.out_dir / "phase4-offtable-report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8")
    print(f"registry: {registry_ok}/{len(registry_attempts)}  "
          f"unseen: {unseen_ok}/{len(unseen)}  "
          f"intermittent: {intermittent_ok}  pairs: {pairs_ok}  gate: {report['gate']}")
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
